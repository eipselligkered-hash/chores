"""v7 smoke test (task sheet, snooze, add/edit/retire, away mode, supplies) against the local mock + phone screenshots.
usage: (python3 -m http.server 8765 &) ; /workspace/.venv-pw/bin/python tests/smoke_features.py [base_url]"""
import sys, os
from playwright.sync_api import sync_playwright
BASE = sys.argv[1] if len(sys.argv) > 1 else "http://localhost:8765/"
OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "screenshots")
errors, results = [], []
def ok(name, cond): results.append((name, bool(cond))); print(("PASS " if cond else "FAIL ") + name)
with sync_playwright() as p:
    b = p.chromium.launch(executable_path="/usr/bin/google-chrome", headless=True)
    ctx = b.new_context(viewport={"width": 390, "height": 844}, device_scale_factor=2, is_mobile=True, has_touch=True,
                        locale="en-IE", service_workers="block")
    ctx.route("**/config.js*", lambda r: r.fulfill(status=200, content_type="application/javascript",
                                                   body="window.CHORES_CONFIG={backend:'mock',cap:300};"))
    pg = ctx.new_page()
    pg.on("console", lambda m: m.type == "error" and errors.append(m.text)); pg.on("pageerror", lambda e: errors.append(str(e)))
    pg.on("dialog", lambda d: d.accept())
    pg.goto(BASE + "?today=2026-11-06"); pg.wait_for_selector(".cap")
    ok("header shows v7", "v7" in pg.inner_text("#today"))
    # supplies line
    ok("You'll need line present", pg.locator("#needs").count() == 1)
    ok("You'll need preview when collapsed", "Degreaser" in pg.inner_text("#needs summary"))
    pg.click("#needs summary"); pg.wait_for_timeout(150)
    ok("You'll need lists degreaser", "Degreaser" in pg.inner_text("#needs ul"))
    pg.screenshot(path=f"{OUT}/weekend_supplies.png")
    pg.click("#needs summary"); pg.wait_for_timeout(150)
    # existing behaviour: tick + undo, long-press
    n0 = pg.locator(".item[data-id]").count()
    pg.locator(".item[data-id] .tick").first.tap(); pg.wait_for_selector("#toast:not([hidden])")
    ok("tick still marks done", "done" in pg.inner_text("#toast")); pg.click("#undo"); pg.wait_for_timeout(300)
    ok("undo restores", pg.locator(".item[data-id]").count() == n0)
    lp = pg.locator(".item[data-id] .body").nth(2); lp.scroll_into_view_if_needed(); box = lp.bounding_box()
    pg.mouse.move(box["x"] + 20, box["y"] + 10); pg.mouse.down(); pg.wait_for_timeout(800); pg.mouse.up(); pg.wait_for_timeout(150)
    ok("long-press still opens date picker", pg.locator("#sheet[open]").count() == 1 and pg.locator("#task-sheet[open]").count() == 0)
    pg.keyboard.press("Escape"); pg.wait_for_timeout(150)
    pg.locator(".item[data-id] .more").first.click(); ok("⋯ still opens date picker", pg.locator("#sheet[open]").count() == 1)
    pg.keyboard.press("Escape"); pg.wait_for_timeout(150)
    # task sheet
    hood = pg.locator(".item[data-id]", has_text="Clean hood above stove")
    hood.locator(".name").tap(); pg.wait_for_selector("#task-sheet[open]")
    txt = pg.inner_text("#task-sheet")
    ok("task sheet: notes, supplies, next due, last done", all(s in txt for s in ["How to", "Degreaser", "Next due", "Last done", "Kitchen", "Quarterly"]))
    pg.screenshot(path=f"{OUT}/task_sheet.png")
    # snooze
    pg.click("#ts-snooze"); pg.wait_for_selector("#toast:not([hidden])")
    ok("snooze toast", "snoozed to Sat 14/11" in pg.inner_text("#toast"))
    ok("snoozed task leaves this weekend", pg.locator(".item[data-id]", has_text="Clean hood above stove").locator(".tick").count() == 0)
    ok("'Not this weekend' section with chip", pg.locator("h2.sec:has-text('Not this weekend')").count() == 1 and pg.locator(".chip.snz").count() >= 1)
    pg.click("#undo"); pg.wait_for_timeout(300)
    ok("snooze undo", pg.locator("h2.sec:has-text('Not this weekend')").count() == 0)
    hood.locator(".name").tap(); pg.wait_for_selector("#task-sheet[open]"); pg.click("#ts-snooze"); pg.wait_for_timeout(300)
    pg.click("text=Next weekend"); pg.wait_for_timeout(200)
    ok("snoozed task on next weekend with chip", pg.locator(".item[data-id]", has_text="Clean hood above stove").locator(".chip.snz").count() == 1)
    pg.click("text=This weekend >> nth=0"); pg.wait_for_timeout(200)
    pg.click("[data-unsnooze]"); pg.wait_for_timeout(300)
    ok("unsnooze from section", pg.locator("h2.sec:has-text('Not this weekend')").count() == 0)
    # done recently -> sheet opens from there too
    hood.locator(".tick").tap(); pg.wait_for_timeout(300)
    pg.locator("[data-tid] .body", has_text="Clean hood above stove").first.tap(); pg.wait_for_selector("#task-sheet[open]")
    ok("sheet from Done recently shows the completion", "Fri 6 Nov 2026" in pg.inner_text("#task-sheet")); pg.keyboard.press("Escape")
    # add task
    pg.click("button[data-tab=all]"); pg.wait_for_selector("details.room")
    pg.click("[data-add]"); pg.wait_for_selector("#edit-sheet[open]")
    pg.fill("#edit-form [name=name]", "Clean grout"); pg.fill("#edit-form [name=room]", "Bathroom")
    pg.select_option("#edit-form [name=frequency]", "Quarterly"); pg.fill("#edit-form [name=effort_min]", "25")
    pg.fill("#edit-form [name=supplies]", "Grout brush, Grout cleaner"); pg.fill("#edit-form [name=last_done]", "2026-08-01")
    pg.click("#ed-save"); pg.wait_for_timeout(400)
    pg.fill("#q", "grout"); pg.wait_for_timeout(200)
    ok("new task listed", pg.locator("details.room .item", has_text="Clean grout").count() == 1)
    new_id = pg.locator("details.room .item", has_text="Clean grout").get_attribute("data-id")
    ok("new task id is a UUID", new_id and len(new_id) == 36)
    # edit (screenshot on an existing task with notes)
    pg.fill("#q", "descale kettle"); pg.wait_for_timeout(200)
    pg.locator("details.room .item .name", has_text="Descale kettle").first.tap(); pg.wait_for_selector("#task-sheet[open]")
    pg.click("#ts-edit"); pg.wait_for_selector("#edit-sheet[open]")
    ok("edit form prefilled", pg.input_value("#edit-form [name=supplies]") == "Descaler or citric acid")
    pg.screenshot(path=f"{OUT}/edit_task.png")
    pg.fill("#edit-form [name=effort_min]", "20"); pg.click("#ed-save"); pg.wait_for_timeout(300)
    ok("edit saved", "20 min" in pg.locator("details.room .item", has_text="Descale kettle").inner_text())
    # retire
    pg.fill("#q", "grout"); pg.wait_for_timeout(200)
    pg.locator("details.room .item .name", has_text="Clean grout").tap(); pg.click("#ts-edit"); pg.wait_for_selector("#edit-sheet[open]")
    pg.uncheck("#edit-form [name=active]"); pg.click("#ed-save"); pg.wait_for_timeout(300)
    ok("retired task hidden", pg.locator("details.room .item[data-id]", has_text="Clean grout").count() == 0 and "Retired" in pg.inner_text("#toast"))
    pg.fill("#q", ""); pg.wait_for_timeout(200)
    ok("Retired section lists it", pg.locator("details.retired", has_text="Clean grout").count() == 1)
    ok("still 123 active rows", pg.locator("details.room:not(.retired) .item").count() == 123)
    # away mode
    pg.click("button[data-tab=weekend]"); pg.wait_for_selector(".cap"); pg.click("text=Next weekend"); pg.wait_for_timeout(200)
    nn = pg.locator(".item[data-id]").count()
    pg.click("#account"); pg.wait_for_selector("#settings[open]")
    pg.fill("#away-from", "2026-11-09"); pg.fill("#away-to", "2026-11-22"); pg.click("#away-add"); pg.wait_for_timeout(400)
    ok("away banner", pg.locator(".banner", has_text="Away 09/11–22/11 – tasks shifted").count() == 1)
    ok(f"next weekend lighter while away ({pg.locator('.item[data-id]').count()} < {nn})", pg.locator(".item[data-id]").count() < nn)
    pg.evaluate("document.querySelector('#toast').hidden = true")
    pg.screenshot(path=f"{OUT}/away_mode.png")
    pg.click("#account"); pg.wait_for_selector("#settings[open]")
    ok("settings lists the away dates", "Mon 09/11 – Sun 22/11" in pg.inner_text("#settings"))
    pg.screenshot(path=f"{OUT}/away_settings.png")
    pg.keyboard.press("Escape"); pg.wait_for_timeout(150)
    pg.click(".banner [data-away-del]"); pg.wait_for_timeout(400)
    ok("away deleted", pg.locator(".banner").count() == 0 and pg.locator(".item[data-id]").count() == nn)
    # persistence across reload (mock = localStorage)
    pg.reload(); pg.wait_for_selector(".cap"); pg.click("button[data-tab=all]"); pg.wait_for_selector("details.room")
    ok("retired task persists after reload", pg.locator("details.retired", has_text="Clean grout").count() == 1)
    b.close()
ok(f"no console errors {errors}", not errors)
print(f"{sum(r for _, r in results)}/{len(results)} smoke checks passed")

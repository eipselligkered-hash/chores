    lp = pg.locator(".item[data-id] .body").nth(2); lp.scroll_into_view_if_needed(); box = lp.bounding_box()
    pg.mouse.move(box["x"] + 20, box["y"] + 10); pg.mouse.down(); pg.wait_for_timeout(800); pg.mouse.up(); pg.wait_for_timeout(150)
    ok("long-press still opens date picker", pg.locator("#sheet[open]").count() == 1 and pg.locator("#task-sheet[open]").count() == 0)
    pg.keyboard.press("Escape"); pg.wait_for_timeout(150)
    pg.locator(".item[data-id] .more").first.click(); ok("⋯ still opens date picker", pg.locator("#sheet[open]").count() == 1)
    pg.keyboard.press("Escape"); pg.wait_for_timeout(150)
    # v12: Planned and Carry over collapsed by default (heading + count + minutes), tap to expand, remembered
    ok("Planned collapsed by default", pg.locator("details.fold[data-fold=planned]:not([open])").count() == 1)
    ok("Carry over collapsed by default", pg.locator("details.fold[data-fold=carry]:not([open])").count() == 1)
    ok("collapsed heading shows count + minutes", "tasks ·" in pg.inner_text("details.fold[data-fold=planned] summary") and "min" in pg.inner_text("details.fold[data-fold=carry] summary"))
    pg.evaluate("document.querySelector('#toast').hidden = true; document.querySelector('.item[data-id] .more').blur()")
    pg.evaluate("(() => { const h = document.querySelector('details.fold[data-fold=planned]'); scrollTo(0, h.getBoundingClientRect().top + scrollY - 420); })()"); pg.wait_for_timeout(150)
    pg.screenshot(path=f"{OUT}/weekend_collapsed.png"); pg.evaluate("scrollTo(0, 0)")
    pg.click("details.fold[data-fold=planned] summary"); pg.wait_for_timeout(150)
    pg.reload(); pg.wait_for_selector(".cap")
    ok("expanded Planned remembered after reload", pg.locator("details.fold[data-fold=planned][open]").count() == 1)
    # task sheet
    hood = pg.locator(".item[data-id]", has_text="Clean hood above stove")
    hood.locator(".name").tap(); pg.wait_for_selector("#task-sheet[open]")
    txt = pg.inner_text("#task-sheet")
    ok("task sheet: notes, supplies, next due, last done", all(s in txt for s in ["How to", "Degreaser", "Next due", "Last done", "Kitchen", "Quarterly"]))
    pg.screenshot(path=f"{OUT}/task_sheet.png")
    # snooze
    pg.click("#ts-snooze"); pg.wait_for_selector("#toast:not([hidden])")
    ok("snooze toast", "snoozed to Sat 14/11" in pg.inner_text("#toast"))
    ok("snoozed task leaves this weekend", pg.locator(".item[data-id]", has_text="Clean hood above stove").locator(".tick").count() == 0)
    ok("'Not this weekend' section with chip", pg.locator("h2.sec:has-text('Not this weekend')").count() == 1 and pg.locator(".chip.snz").count() >= 1)
    pg.click("#undo"); pg.wait_for_timeout(300)
    ok("snooze undo", pg.locator("h2.sec:has-text('Not this weekend')").count() == 0)
    hood.locator(".name").tap(); pg.wait_for_selector("#task-sheet[open]"); pg.click("#ts-snooze"); pg.wait_for_timeout(300)
    pg.click("text=Next weekend"); pg.wait_for_timeout(200)
    ok("snoozed task on next weekend with chip", pg.locator(".item[data-id]", has_text="Clean hood above stove").locator(".chip.snz").count() == 1)
    pg.click("text=This weekend >> nth=0"); pg.wait_for_timeout(200)
    pg.click("[data-unsnooze]"); pg.wait_for_timeout(300)
    ok("unsnooze from section", pg.locator("h2.sec:has-text('Not this weekend')").count() == 0)
    # done recently -> sheet opens from there too
    hood.locator(".tick").tap(); pg.wait_for_timeout(300)
    pg.locator("[data-tid] .body", has_text="Clean hood above stove").first.tap(); pg.wait_for_selector("#task-sheet[open]")
    ok("sheet from Done recently shows the completion", "Fri 6 Nov 2026" in pg.inner_text("#task-sheet")); pg.keyboard.press("Escape")
    # add task
    pg.click("button[data-tab=all]"); pg.wait_for_selector("details.room")
    pg.click("[data-add]"); pg.wait_for_selector("#edit-sheet[open]")
    pg.fill("#edit-form [name=name]", "Clean grout"); pg.fill("#edit-form [name=room]", "Bathroom")
    pg.select_option("#edit-form [name=frequency]", "Quarterly"); pg.fill("#edit-form [name=effort_min]", "25")
    pg.fill("#edit-form [name=supplies]", "Grout brush, Grout cleaner"); pg.fill("#edit-form [name=last_done]", "2026-08-01")
    pg.click("#ed-save"); pg.wait_for_timeout(400)
    pg.fill("#q", "grout"); pg.wait_for_timeout(200)
    ok("new task listed", pg.locator("details.room .item", has_text="Clean grout").count() == 1)
    new_id = pg.locator("details.room .item", has_text="Clean grout").get_attribute("data-id")
    ok("new task id is a UUID", new_id and len(new_id) == 36)
    # edit (screenshot on an existing task with notes)
    pg.fill("#q", "descale kettle"); pg.wait_for_timeout(200)
    pg.locator("details.room .item .name", has_text="Descale kettle").first.tap(); pg.wait_for_selector("#task-sheet[open]")
    pg.click("#ts-edit"); pg.wait_for_selector("#edit-sheet[open]")
    ok("edit form prefilled", pg.input_value("#edit-form [name=supplies]") == "Descaler or citric acid")
    pg.screenshot(path=f"{OUT}/edit_task.png")
    pg.fill("#edit-form [name=effort_min]", "20"); pg.click("#ed-save"); pg.wait_for_timeout(300)
    ok("edit saved", "20 min" in pg.locator("details.room .item", has_text="Descale kettle").inner_text())
